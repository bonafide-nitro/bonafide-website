// Issue #195: build the PRIVATE GoDaddy staging payload. Offline: no network, no deploy, no secret is read except the two
// non-credential paths below (supplied by the workflow from GitHub secrets and only ever embedded in the generated .htaccess).
//
//   node scripts/staging-package.mjs site     --dist dist --out staging-out          (build job, no secrets)
//       copies dist/ to <out>/site, forces a blanket-Disallow robots.txt (defense in depth; the real gate is HTTP auth),
//       and fails if the build is not a clean MOCK/DISABLED-contact build.
//   node scripts/staging-package.mjs assemble --site <dir> --kind full|protect --out staging-out
//       env STG_DOCROOT, STG_AUTH_FILE (absolute paths on the host), GITHUB_SHA, and for kind=protect STG_NONCE.
//       Renders the staging .htaccess from the committed overlay template, runs the staging preflight (rejects placeholders,
//       a missing auth/noindex line, or an AuthUserFile inside the docroot), writes the marker and a deterministic .tgz.
//       kind=protect is a tiny tree (protection + placeholder page + one nonce probe file) that is installed and PROVEN before
//       any build bytes are uploaded.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { scanArtifact, walkTree } from './check-release-artifact.mjs';
import { loadBaseline } from '../src/lib/data.mjs';
import { preflight, STAGING_OVERLAY_PATH, PLACEHOLDER_AUTH_FILE, PLACEHOLDER_AUTH_REALM } from './build-apache-config.mjs';

export const STAGING_HOSTNAME = 'staging.bonafidenitro.com';
export const MARKER = '.bonafide-staging';
export const AUTH_REALM = 'Bona Fide staging (private)';
export const STAGING_ROBOTS = 'User-agent: *\nDisallow: /\n';
// A staging build must never be able to reach the live Brevo handler or carry a provider key.
export const LIVE_CONTACT_PATTERNS = [/contact-submit/i, /api\.brevo\.com/i, /api-key/i, /xkeysib-/i, /sendinblue/i];

const text = (f) => fs.readFileSync(f).toString('latin1');
const textFiles = (dir) => walkTree(dir).files.filter((f) => /\.(html?|js|mjs|json|txt|xml|css|svg|webmanifest)$/i.test(f));

export const contactProblems = (dir) => {
  const out = [];
  for (const rel of textFiles(dir)) {
    for (const re of LIVE_CONTACT_PATTERNS) if (re.test(text(path.join(dir, rel)))) out.push(`${rel}: live contact/provider reference ${re}`);
  }
  return out;
};

export const makeSite = ({ dist, out }) => {
  const distDir = path.resolve(dist);
  if (!fs.existsSync(path.join(distDir, 'index.html'))) throw new Error('dist/index.html missing: run `npm run build` first');
  const findings = scanArtifact(distDir, loadBaseline().preservationRules.forbiddenBuildStrings);
  if (findings.length) throw new Error(`artifact findings:\n${findings.map((f) => `[${f.rule}] ${f.file}: ${f.detail}`).join('\n')}`);
  const bad = contactProblems(distDir);
  if (bad.length) throw new Error(`staging build must be mock/disabled contact only:\n${bad.join('\n')}`);
  for (const forbidden of ['.htaccess', MARKER]) {
    if (fs.existsSync(path.join(distDir, forbidden))) throw new Error(`${forbidden} must not be part of the build`);
  }
  const site = path.join(path.resolve(out), 'site');
  fs.rmSync(path.resolve(out), { recursive: true, force: true });
  fs.mkdirSync(site, { recursive: true });
  fs.cpSync(distDir, site, { recursive: true });
  fs.writeFileSync(path.join(site, 'robots.txt'), STAGING_ROBOTS);
  return site;
};

export const PUBLIC_HTACCESS = [
  '# Bona Fide PUBLIC noindex staging, generated by scripts/staging-package.mjs (Issue #198). NOT access control: anyone with the link can view it.',
  '<IfModule !mod_headers.c>',
  '  # noindex cannot be enforced without mod_headers: fail closed.',
  '  Require all denied',
  '</IfModule>',
  '<IfModule mod_headers.c>',
  '  Header always set X-Robots-Tag "noindex, nofollow"',
  '</IfModule>',
  '',
].join('\n');

export const renderHtaccess = ({ docroot, authFile, access = 'basic' }) => {
  if (access === 'public') {
    const problems = preflight(PUBLIC_HTACCESS, 'staging-public', { docroot });
    if (problems.length) throw new Error(`public staging .htaccess preflight BLOCKED:\n- ${problems.join('\n- ')}`);
    return PUBLIC_HTACCESS;
  }
  if (access !== 'basic') throw new Error('access must be basic|public');
  const tpl = fs.readFileSync(STAGING_OVERLAY_PATH, 'utf8');
  if (!tpl.includes(PLACEHOLDER_AUTH_FILE) || !tpl.includes(PLACEHOLDER_AUTH_REALM)) throw new Error('overlay template placeholders changed');
  const body = tpl.replace(PLACEHOLDER_AUTH_REALM, AUTH_REALM).replace(PLACEHOLDER_AUTH_FILE, authFile);
  // The template's leading comment says it is unusable until completed; keep the file free of the template banner.
  const out = body.split('\n').filter((l) => !l.startsWith('# GENERATED FILE') && !l.startsWith('# STAGING-ONLY') && !l.startsWith('# Not usable') && !l.startsWith('# human created')).join('\n');
  const header = '# Bona Fide STAGING protection, generated by scripts/staging-package.mjs (Issue #195). HTTP Basic auth + server-enforced noindex.\n';
  const problems = preflight(header + out, 'staging', { docroot });
  if (problems.length) throw new Error(`staging .htaccess preflight BLOCKED:\n- ${problems.join('\n- ')}`);
  return header + out;
};

const sha256 = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');

export const assemble = ({ site, kind, out, docroot, authFile, commit, nonce, access = 'basic' }) => {
  if (!['full', 'protect'].includes(kind)) throw new Error('kind must be full|protect');
  if (!/^[0-9a-f]{40}$/.test(commit ?? '')) throw new Error('GITHUB_SHA must be a 40-character commit SHA');
  if (kind === 'protect' && !/^[0-9a-f]{32,64}$/.test(nonce ?? '')) throw new Error('protect kind needs STG_NONCE (hex)');
  const htaccess = renderHtaccess({ docroot, authFile, access });
  const outDir = path.resolve(out);
  const tree = path.join(outDir, `tree-${kind}`);
  fs.rmSync(tree, { recursive: true, force: true });
  fs.mkdirSync(tree, { recursive: true });
  if (kind === 'full') {
    const siteDir = path.resolve(site);
    if (!fs.existsSync(path.join(siteDir, 'index.html'))) throw new Error('site/index.html missing');
    if (contactProblems(siteDir).length) throw new Error('site has live contact/provider references');
    fs.cpSync(siteDir, tree, { recursive: true });
    for (const f of ['.htaccess', MARKER, '.well-known']) if (fs.existsSync(path.join(tree, f))) throw new Error(`${f} must not be in the site tree`);
    fs.writeFileSync(path.join(tree, 'robots.txt'), STAGING_ROBOTS);
  } else {
    fs.writeFileSync(path.join(tree, 'robots.txt'), STAGING_ROBOTS);
    fs.writeFileSync(path.join(tree, 'index.html'), `<!doctype html><meta charset="utf-8"><meta name="robots" content="noindex,nofollow"><title>Staging</title><p>${access === 'public' ? 'Public' : 'Private'} staging placeholder.</p>\n`);
    fs.writeFileSync(path.join(tree, `bf-probe-${nonce}.txt`), `${nonce}\n`);
  }
  fs.writeFileSync(path.join(tree, '.htaccess'), htaccess);
  fs.writeFileSync(path.join(tree, MARKER), `commit=${commit}\nkind=${kind}\naccess=${access}\n`);
  const tgz = path.join(outDir, `staging-${kind}.tgz`);
  // Deterministic: sorted names, fixed mtime/owner. gzip -n drops the timestamp from the header.
  const tar = spawnSync('tar', ['--sort=name', '--mtime=@0', '--owner=0', '--group=0', '--numeric-owner', '-cf', '-', '-C', tree, '.'], { maxBuffer: 1 << 30 });
  if (tar.status !== 0) throw new Error('tar failed');
  const gz = spawnSync('gzip', ['-n', '-9'], { input: tar.stdout, maxBuffer: 1 << 30 });
  if (gz.status !== 0) throw new Error('gzip failed');
  fs.writeFileSync(tgz, gz.stdout);
  const digest = sha256(tgz);
  fs.writeFileSync(`${tgz}.sha256`, `${digest}\n`);
  return { tgz, digest, fileCount: walkTree(tree).files.length };
};

if (import.meta.url === `file://${process.argv[1]}`) {
  const argv = process.argv.slice(2);
  const val = (n, d) => { const i = argv.indexOf(n); return i === -1 ? d : argv[i + 1]; };
  try {
    if (argv[0] === 'site') {
      const site = makeSite({ dist: val('--dist', 'dist'), out: val('--out', 'staging-out') });
      console.log(`OK: staging site tree prepared (${walkTree(site).files.length} files)`);
    } else if (argv[0] === 'assemble') {
      const r = assemble({
        site: val('--site', 'staging-out/site'), kind: val('--kind', 'full'), out: val('--out', 'staging-out'),
        docroot: process.env.STG_DOCROOT, authFile: process.env.STG_AUTH_FILE, access: process.env.STG_ACCESS || 'basic', commit: process.env.GITHUB_SHA, nonce: process.env.STG_NONCE,
      });
      console.log(`OK: ${path.basename(r.tgz)} ${r.fileCount} files sha256=${r.digest}`);
    } else throw new Error('usage: site|assemble');
  } catch (e) { console.error(e.message); process.exit(1); }
}
